package main

import "fmt"

func main() {
	var a bool = true
	var b int = 5
	var c float32 = 3.14
	var d string = "Hi!"

	fmt.Println("Boolean: ", a)
	fmt.Println("Integer: ", b)
	fmt.Println("Float:   ", c)
	fmt.Println("String:  ", d)
}
