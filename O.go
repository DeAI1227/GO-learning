package main

import "fmt"

// ============================================================
// O.go｜第 17 章：函式 func（完整 30 分鐘課）
// 教學格式：每個函式上方都有「加了什麼／為什麼這樣寫」
// 跑法：go run O.go
// ============================================================

func main() {
	fmt.Println("===== 第 1～5 分鐘：先看整支程式能跑 =====")

	fmt.Println("\n--- 1) 無參數、無回傳 ---")
	sayHello()

	fmt.Println("\n--- 2) 有參數 ---")
	greet("惟理")

	fmt.Println("\n--- 3) 有回傳值 ---")
	sum := add(3, 5)
	fmt.Println("3 + 5 =", sum)

	fmt.Println("\n--- 4) 同型別參數縮寫 ---")
	fmt.Println("10 - 4 =", sub(10, 4))

	fmt.Println("\n--- 5) 多回傳值 ---")
	q, r := divmod(17, 5)
	fmt.Println("17 / 5 → 商=", q, "餘=", r)
	qOnly, _ := divmod(17, 5)
	fmt.Println("只要商 =", qOnly)

	fmt.Println("\n--- 6) 命名回傳 ---")
	fmt.Println("面積=", rectArea(4, 6))

	fmt.Println("\n===== 第 15～25 分鐘：作業函式（slice）=====")
	nums := []int{10, 20, 30, 40}
	fmt.Println("nums =", nums)
	fmt.Println("總和=", sumSlice(nums))
	fmt.Println("最大=", maxSlice(nums))
	fmt.Println("平均=", avg(nums))
}

// ------------------------------------------------------------
// 1) 無參數、無回傳
// 加了什麼：func sayHello() { ... }，括號空、後面沒回傳型別
// 為什麼：只做事（印字），不需要算出值給外面用
// ------------------------------------------------------------
func sayHello() {
	fmt.Println("Hello, Go function!")
}

// ------------------------------------------------------------
// 2) 有參數
// 加了什麼：name string —— 呼叫時要傳一個字串進來
// 為什麼：把「會變的名字」抽成參數，同一個函式能服務很多人名
// ------------------------------------------------------------
func greet(name string) {
	fmt.Println("你好,", name)
}

// ------------------------------------------------------------
// 3) 有回傳值
// 加了什麼：兩個 int 參數 + 回傳一個 int；用 return 送出結果
// 為什麼：加法邏輯命名成 add 方便重用；呼叫端用變數接住結果
// ------------------------------------------------------------
func add(a int, b int) int {
	return a + b
}

// ------------------------------------------------------------
// 4) 同型別參數縮寫 + 作業 sub
// 加了什麼：a, b int 寫在一起；回傳 a - b
// 為什麼：型別相同可少寫一次 int；減法同樣值得包成可重用函式
// ------------------------------------------------------------
func sub(a, b int) int {
	return a - b
}

// ------------------------------------------------------------
// 5) 多回傳值
// 加了什麼：(int, int) 一次回傳兩個值；return 商, 餘
// 為什麼：成對結果用多回傳最自然，不必硬塞進怪結構
// ------------------------------------------------------------
func divmod(a, b int) (int, int) {
	return a / b, a % b
}

// ------------------------------------------------------------
// 6) 命名回傳
// 加了什麼：(area int) 先替回傳值取名；最後可裸 return
// 為什麼：回傳值在函式內賦值後自動送出；初學先會看即可
// ------------------------------------------------------------
func rectArea(width, height int) (area int) {
	area = width * height
	return
}

// ------------------------------------------------------------
// 7) slice 總和（複習 for range + 包成函式）
// 加了什麼：參數 nums []int；用 range 累加；return total
// 為什麼：你已會的迴圈，包起來後任何地方都能 sumSlice(某slice)
// ------------------------------------------------------------
func sumSlice(nums []int) int {
	total := 0
	for _, n := range nums {
		total += n
	}
	return total
}

// ------------------------------------------------------------
// 8) slice 最大值
// 加了什麼：先處理空 slice；再假設第一個最大並比較後面
// 為什麼：空的不能取 [0]；「先假設再比較」是找最大值的安全寫法
// ------------------------------------------------------------
func maxSlice(nums []int) int {
	if len(nums) == 0 {
		return 0
	}
	m := nums[0]
	for _, n := range nums[1:] {
		if n > m {
			m = n
		}
	}
	return m
}

// ------------------------------------------------------------
// 9) 作業 avg：平均值（回傳 float64）
// 加了什麼：回傳 float64；用 float64(...) 做型別轉換後相除
// 為什麼：整數相除會捨去小數；平均需要小數所以換成 float64
// ------------------------------------------------------------
func avg(nums []int) float64 {
	if len(nums) == 0 {
		return 0
	}
	return float64(sumSlice(nums)) / float64(len(nums))
}
